/* Actual dictionary UI renderer, real ECDICT data and font; PC only. */
#include "../runtime/apps/dictionary/ui.h"
#include "../runtime/apps/emulators/platform.h"
#include <assert.h>
#include <stdio.h>
#include <string.h>
static struct dx_ui ui;
static void frame(const char *name) {
  dx_ui_render(&ui);
  char p[256];
  snprintf(p, sizeof p, "work/dictionary-preview/%s.rgb565", name);
  FILE *f = fopen(p, "wb");
  assert(f);
  assert(fwrite(ep_canvas, 2, 240 * 432, f) == 240 * 432);
  assert(!fclose(f));
}
int main(void) {
  assert(dx_ui_open(&ui, "work/dictionary-data/lexicon.dic",
                    "work/dictionary-data/font.bin"));
  frame("01-home");
  strcpy(ui.input.query, "hello");
  dx_ui_refresh(&ui);
  assert(ui.result_count > 0);
  frame("02-search");
  strcpy(ui.input.query, "dictionary");
  dx_ui_refresh(&ui);
  assert(ui.result_count > 0);
  dx_ui_touch(&ui, 30, 86, 1000);
  assert(ui.mode == DX_ARTICLE);
  frame("03-entry");
  printf("Dictionary %u entries; 3 frames generated by production UI.\n",
         ui.dict.count);
  dx_ui_close(&ui);
  return 0;
}
